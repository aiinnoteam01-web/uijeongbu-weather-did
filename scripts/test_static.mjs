import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const script=html.match(/<script>([\s\S]*?)<\/script>/)[1];
const now=new Date(),kst=new Date(now.getTime()+9*3600000);
const date=kst.toISOString().slice(0,10).replaceAll('-',''),hour=kst.getUTCHours();
const rows=['의정부','신곡'].flatMap(SPOT_NM=>[Math.max(0,hour-1),hour].map(h=>({SPOT_NM,MESURE_DE:date,MESURE_TM:String(h).padStart(2,'0'),TP_INFO:0,RAINF_1HR_INFO:0})));
const elements={},calls=[];
const context=vm.createContext({Date,Intl,AbortSignal,document:{querySelector:selector=>elements[selector]??={innerHTML:'',textContent:'',classList:{toggle(){}}}},fetch:async url=>{calls.push(url);return {ok:true,json:async()=>({rows,generatedAt:now.toISOString(),error:''})}},setTimeout(fn,ms){if(ms===0)setImmediate(fn);return 1},clearTimeout(){},setInterval(){}});
vm.runInContext(script,context);
await new Promise(resolve=>setImmediate(()=>setImmediate(()=>setImmediate(resolve))));
assert.equal(calls.length,1);assert(calls[0].startsWith('./data/observations.json?'));
assert(elements['#board'].innerHTML.includes('의정부 지점'));
assert(elements['#board'].innerHTML.includes('신곡 지점'));
assert.equal(elements['#refreshButton'].disabled,false);
elements['#refreshButton'].onclick();assert.equal(elements['#refreshButton'].disabled,true);
await new Promise(resolve=>setImmediate(()=>setImmediate(()=>setImmediate(resolve))));
assert.equal(calls.length,2);assert.equal(elements['#refreshButton'].disabled,false);
console.log('Passed: project-relative JSON, one shared JSON read per refresh, both stations and manual refresh.');
